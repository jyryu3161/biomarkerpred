assert <- function(x, message) if (!isTRUE(x)) stop(message, call. = FALSE)
near <- function(x,y,tol=1e-10) assert(isTRUE(all.equal(as.numeric(x),as.numeric(y),tolerance=tol)), paste(x,"!=",y))
expect_error <- function(code, pattern) {
  error <- tryCatch({force(code);NULL},error=identity)
  assert(inherits(error,"error"),"Expected an error")
  assert(grepl(pattern,conditionMessage(error),ignore.case=TRUE),conditionMessage(error))
  invisible(error)
}
